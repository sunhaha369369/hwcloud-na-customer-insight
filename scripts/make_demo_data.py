def month_index(m):
    y, mo = m.split("-")
    return int(y) * 12 + int(mo) - 1


def generate(out):
    a = argparse.Namespace(out=out)
    os.makedirs(a.out, exist_ok=True)

    # ---------------- accounts（中文表头，验证别名映射）
    with open(os.path.join(a.out, "accounts.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["客户编号", "客户名称", "所属行业", "区域", "是否NA客户", "客户经理",
                    "签约日期", "合同到期日", "员工规模", "营收规模"])
        for acc in ACCOUNTS:
            w.writerow([acc[0], acc[1], acc[2], acc[3], acc[4], acc[5], acc[6], acc[7],
                        random.choice([800, 3000, 12000, 45000]), random.choice(["10-50亿", "50-200亿", "200亿以上"])])

    # ---------------- transactions（英文表头，验证英文别名）
    tx_rows = []
    for acc in ACCOUNTS:
        aid, _, _, _, _, _, _, _, base, growth, prods, start = acc
        if not prods:
            continue
        for m in MONTHS:
            if month_index(m) < month_index(start):
                continue
            k = month_index(m) - month_index(MONTHS[0])
            trend = (1 + growth) ** k
            seasonal = 1 + 0.06 * ((k % 12) in (2, 3, 11)) - 0.05 * ((k % 12) in (1,))
            for prod, share in prods.items():
                noise = random.uniform(0.93, 1.07)
                amt = base * share * trend * seasonal * noise
                if aid == "ACC006" and month_index(m) >= month_index("2026-01"):
                    amt *= 0.82                    # 断崖：预算收紧后削减
                if aid == "ACC011" and month_index(m) >= month_index("2026-03"):
                    amt = 0                        # 已流失
                if amt <= 0:
                    continue
                tx_rows.append([aid, m, prod, f"{prod}-标准型", round(amt, 2),
                                round(amt / random.uniform(0.72, 0.95), 2),
                                random.choice(["按需", "包年包月", "预留实例"])])
    with open(os.path.join(a.out, "transactions.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["account_id", "month", "product_line", "product_sku", "amount",
                    "list_amount", "consumption_type"])
        w.writerows(tx_rows)

    # ---------------- behavior（中文表头 + 部分英文）
    beh_rows = []
    for aid, p in BEHAVIOR.items():
        acc = next(x for x in ACCOUNTS if x[0] == aid)
        start = acc[11] if acc[8] > 0 else "2026-01"
        for m in MONTHS:
            if month_index(m) < month_index(start):
                continue
            k = month_index(m) - month_index(MONTHS[0])
            t = (1 + p["trend"]) ** k
            deep = 0.35 if (aid == "ACC011" and month_index(m) >= month_index("2026-01")) else 1.0
            deep2 = 0.55 if (aid in ("ACC006", "ACC008") and month_index(m) >= month_index("2026-03")) else 1.0
            beh_rows.append([
                aid, m,
                round(p["mau"] * t * deep * deep2),
                round(p["mau"] * p["login"] * t * deep * deep2),
                round(p["api"] * t * deep * deep2),
                round(p["res"] * t * deep2),
                random.randint(2, 22),
                max(0, round(p["ticket"] + random.uniform(-2, 4) + (3 if deep2 < 1 else 0))),
                round(min(1.0, p["usage"] * (1 + 0.006 * k) * (0.62 if deep2 < 1 else 1)), 2),
                random.choice([0, 0, 0, 1, 2]) if aid in ("ACC007", "ACC010") else 0,
            ])
    with open(os.path.join(a.out, "behavior.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["客户ID", "月份", "MAU", "登录次数", "API调用量", "资源数", "新增资源数",
                    "工单数", "资源使用率", "试用次数"])
        w.writerows(beh_rows)

    # ---------------- feedback（中文表头）
    with open(os.path.join(a.out, "feedback.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["反馈ID", "客户ID", "日期", "来源", "问题类型", "反馈内容", "严重度", "是否升级", "NPS"])
        for i, (aid, d, src, cat, text, sev, esc) in enumerate(FEEDBACK, 1):
            w.writerow([f"FB{i:04d}", aid, d, src, cat, text, sev, esc,
                        NPS.get(aid) if src == "NPS调研" else ""])

    # ---------------- competitor
    with open(os.path.join(a.out, "competitor.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["客户ID", "日期", "竞品", "信号类型", "置信度", "预估份额变化", "证据"])
        for r in COMPETITOR:
            w.writerow(list(r))

    # ---------------- churn
    with open(os.path.join(a.out, "churn.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["客户ID", "流失日期", "原因编码", "流失原因", "流失金额", "流失竞品"])
        for aid, (d, code, reason, lost, comp) in CHURNED.items():
            w.writerow([aid, d, code, reason, lost, comp])

    print(f"✓ 演示数据已生成 → {os.path.abspath(a.out)}")
    print(f"  交易 {len(tx_rows)} 行 / 行为 {len(beh_rows)} 行 / 反馈 {len(FEEDBACK)} 条 / 客户 {len(ACCOUNTS)} 个")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="./demo-data")
    generate(ap.parse_args().out)


if __name__ == "__main__":
    main()
